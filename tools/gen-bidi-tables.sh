#!/bin/sh
# Regenerates src/bidi/tables.zig from the pinned Unicode data (run test/fetch-ucd.sh first).
# classes   = every explicit Bidi_Class line of DerivedBidiClass.txt (the file is grouped by class, so sorted here).
# defaults  = its "@missing" lines for unassigned code points in RTL/currency blocks (anything else is L).
# brackets  = Bidi_Paired_Bracket + Bidi_Paired_Bracket_Type from BidiBrackets.txt.
set -eu
cd "$(dirname "$0")/.."
U=test/ucd
# Prefix each emitted line with a zero-padded sort key, sort, drop the key.
sorted() { sort | cut -d'|' -f2-; }
{
  echo "//! GENERATED by tools/gen-bidi-tables.sh from $(head -1 $U/DerivedBidiClass.txt | sed 's/^# //') and $(head -1 $U/BidiBrackets.txt | sed 's/^# //'). Do not edit. Unicode License v3, see NOTICE."
  echo 'const bidi = @import("bidi.zig");'
  echo
  echo '/// Explicit Bidi_Class ranges, sorted by code point. Code points not listed fall back to `defaults`, then L.'
  echo 'pub const classes = [_]bidi.ClassRange{'
  awk -F';' '/^[0-9A-F]/ {
    gsub(/[ \t]/, "", $1); split($1, r, /\.\./); lo = r[1]; hi = (r[2] == "" ? r[1] : r[2])
    split($2, c, " "); k = lo; while (length(k) < 6) k = "0" k
    printf "%s|    .{ .lo = 0x%s, .hi = 0x%s, .class = .%s },\n", k, lo, hi, c[1]
  }' $U/DerivedBidiClass.txt | sorted
  echo '};'
  echo
  echo '/// Default Bidi_Class of unassigned code points in right-to-left and currency blocks, sorted, disjoint.'
  echo 'pub const defaults = [_]bidi.ClassRange{'
  awk '/^# @missing: / && !/0000\.\.10FFFF/ {
    split($3, r, /\.\./); sub(/;$/, "", r[2]); cls = $4
    if (cls == "Right_To_Left") cls = "R"; else if (cls == "Arabic_Letter") cls = "AL"; else if (cls == "European_Terminator") cls = "ET"; else { print "unknown default class " cls > "/dev/stderr"; exit 1 }
    printf "    .{ .lo = 0x%s, .hi = 0x%s, .class = .%s },\n", r[1], r[2], cls
  }' $U/DerivedBidiClass.txt
  echo '};'
  echo
  echo '/// Paired brackets, sorted by code point.'
  echo 'pub const brackets = [_]bidi.Bracket{'
  awk -F';' '/^[0-9A-F]/ {
    gsub(/[ \t]/, "", $1); gsub(/[ \t]/, "", $2); split($3, t, " ")
    printf "    .{ .cp = 0x%s, .pair = 0x%s, .open = %s },\n", $1, $2, (t[1] == "o" ? "true" : "false")
  }' $U/BidiBrackets.txt
  echo '};'
} > src/bidi/tables.zig
